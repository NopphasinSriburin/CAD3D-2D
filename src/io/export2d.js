import ACI from 'dxf-parser/dist/AutoCadColorIndex.js';
import { UNITS } from '../core/units.js';
import {
  arcPoints, boundsValid, drawingBounds, isLayerVisible, normSweep, resolveColor, resolveLineType, resolveWeight,
} from '../cad/drawing.js';

export const PAPERS = { A4: [297, 210], A3: [420, 297], A2: [594, 420], A1: [841, 594], A0: [1189, 841] };

const FONT_STACK = "Arial, 'Helvetica Neue', 'Leelawadee UI', Tahoma, 'Noto Sans Thai', sans-serif";
const DASH_MM = [3, 1.5];

/** Bounds + scale for a drawing. Sheets use their paper frame, flat drawings get a small margin at 1:1. */
function layoutFor(drawing, sheet) {
  if (sheet) return { b: sheet.frame, k: sheet.k };
  const b = drawingBounds(drawing);
  if (!boundsValid(b)) throw new Error('DRAWING_EMPTY');
  const w = b.maxX - b.minX || 1;
  const h = b.maxY - b.minY || 1;
  const m = Math.max(w, h) * 0.03;
  return { b: { minX: b.minX - m, minY: b.minY - m, maxX: b.maxX + m, maxY: b.maxY + m }, k: UNITS[drawing.units]?.toMM || 1 };
}

function numFormatter(b) {
  const span = Math.max(b.maxX - b.minX, b.maxY - b.minY, 1e-9);
  const decimals = Math.min(9, Math.max(2, 6 - Math.floor(Math.log10(span))));
  const f = 10 ** decimals;
  return (v) => String(Math.round(v * f) / f);
}

function escapeXml(s) {
  return String(s).replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&apos;' })[c]);
}

/* ------------------------------------------------------------------ SVG */

export function drawingToSVG(drawing, { sheet = null, pixelWidth = null, background = null, linePx = null } = {}) {
  const { b, k } = layoutFor(drawing, sheet);
  const n = numFormatter(b);
  const bw = b.maxX - b.minX;
  const bh = b.maxY - b.minY;
  const pxPerUnit = pixelWidth ? pixelWidth / bw : null;

  const lineWidth = (weight) => {
    if (linePx && pxPerUnit) return (linePx * (weight / 0.25)) / pxPerUnit;
    return weight / k;
  };
  const dashArray = linePx && pxPerUnit ? [(linePx * 5) / pxPerUnit, (linePx * 3) / pxPerUnit] : [DASH_MM[0] / k, DASH_MM[1] / k];

  const groups = new Map();
  const texts = [];
  for (const e of drawing.entities) {
    if (!isLayerVisible(drawing, e.layer)) continue;
    const color = resolveColor(drawing, e) || '#000000';
    if (e.type === 'text') {
      texts.push({ e, color });
      continue;
    }
    const dashed = resolveLineType(drawing, e) === 'dashed';
    const weight = resolveWeight(drawing, e);
    const fill = e.type === 'polyline' && e.fill;
    const key = `${color}|${dashed}|${weight}|${fill}`;
    let g = groups.get(key);
    if (!g) groups.set(key, (g = { color, dashed, weight, fill, d: [] }));
    switch (e.type) {
      case 'polyline': {
        const p = e.points;
        let d = `M${n(p[0][0])} ${n(p[0][1])}`;
        for (let i = 1; i < p.length; i++) d += `L${n(p[i][0])} ${n(p[i][1])}`;
        if (e.closed) d += 'Z';
        g.d.push(d);
        break;
      }
      case 'circle': {
        const [cx, cy] = e.c;
        const r = n(e.r);
        g.d.push(`M${n(cx + e.r)} ${n(cy)}A${r} ${r} 0 1 1 ${n(cx - e.r)} ${n(cy)}A${r} ${r} 0 1 1 ${n(cx + e.r)} ${n(cy)}Z`);
        break;
      }
      case 'arc': {
        const sweep = normSweep(e.a0, e.a1);
        const [cx, cy] = e.c;
        const x0 = cx + e.r * Math.cos(e.a0);
        const y0 = cy + e.r * Math.sin(e.a0);
        const x1 = cx + e.r * Math.cos(e.a0 + sweep);
        const y1 = cy + e.r * Math.sin(e.a0 + sweep);
        const r = n(e.r);
        g.d.push(`M${n(x0)} ${n(y0)}A${r} ${r} 0 ${sweep > Math.PI ? 1 : 0} 1 ${n(x1)} ${n(y1)}`);
        break;
      }
      default:
        break;
    }
  }

  const widthAttr = pixelWidth ? `${pixelWidth}` : `${n(bw * k)}mm`;
  const heightAttr = pixelWidth ? `${Math.round((pixelWidth * bh) / bw)}` : `${n(bh * k)}mm`;
  const out = [];
  out.push(`<?xml version="1.0" encoding="UTF-8"?>`);
  out.push(`<svg xmlns="http://www.w3.org/2000/svg" width="${widthAttr}" height="${heightAttr}" viewBox="${n(b.minX)} ${n(-b.maxY)} ${n(bw)} ${n(bh)}">`);
  out.push(`<!-- Generated by MorphCAD · units: ${drawing.units}${sheet ? ` · scale ${sheet.scaleLabel} · ${sheet.paper}` : ''} -->`);
  if (background) out.push(`<rect x="${n(b.minX)}" y="${n(-b.maxY)}" width="${n(bw)}" height="${n(bh)}" fill="${background}"/>`);
  out.push(`<g transform="scale(1,-1)" fill="none" stroke-linecap="round" stroke-linejoin="round">`);
  for (const g of groups.values()) {
    const lw = lineWidth(g.weight);
    const dash = g.dashed ? ` stroke-dasharray="${n(dashArray[0])} ${n(dashArray[1])}"` : '';
    const fill = g.fill ? ` fill="${g.color}"` : '';
    out.push(`<path d="${g.d.join('')}" stroke="${g.color}" stroke-width="${n(lw)}"${dash}${fill}/>`);
  }
  for (const { e, color } of texts) {
    const size = e.h * 1.4;
    const anchor = e.align === 'center' ? 'middle' : e.align === 'right' ? 'end' : 'start';
    const lines = String(e.text).split('\n');
    const baseShift = e.valign === 'middle' ? e.h / 2 : e.valign === 'top' ? e.h : 0;
    const rotDeg = -((e.rot || 0) * 180) / Math.PI;
    const tspans = lines
      .map((line, i) => `<tspan x="0" y="${n(i * e.h * 1.6 + baseShift)}">${escapeXml(line)}</tspan>`)
      .join('');
    out.push(
      `<text transform="translate(${n(e.p[0])} ${n(e.p[1])}) scale(1,-1) rotate(${n(rotDeg)})" font-family="${FONT_STACK}" font-size="${n(size)}" fill="${color}" stroke="none" text-anchor="${anchor}">${tspans}</text>`,
    );
  }
  out.push(`</g></svg>`);
  return out.join('\n');
}

/* ------------------------------------------------------------------ PNG */

export async function drawingToPNG(drawing, { sheet = null, width = 2048, background = '#ffffff' } = {}) {
  const svg = drawingToSVG(drawing, {
    sheet,
    pixelWidth: width,
    background: background === 'transparent' ? null : background,
    linePx: sheet ? null : Math.max(1.2, width / 1400),
  });
  const url = URL.createObjectURL(new Blob([svg], { type: 'image/svg+xml' }));
  try {
    const img = new Image();
    img.src = url;
    await img.decode();
    const canvas = document.createElement('canvas');
    canvas.width = img.naturalWidth || width;
    canvas.height = img.naturalHeight || Math.round(width * 0.7);
    const ctx = canvas.getContext('2d');
    ctx.drawImage(img, 0, 0, canvas.width, canvas.height);
    return await new Promise((resolve, reject) => canvas.toBlob((b) => (b ? resolve(b) : reject(new Error('PNG_FAILED'))), 'image/png'));
  } finally {
    URL.revokeObjectURL(url);
  }
}

/* ------------------------------------------------------------------ DXF (R12) */

const aciCache = new Map();
function nearestAci(hex) {
  if (!hex) return 7;
  if (aciCache.has(hex)) return aciCache.get(hex);
  const v = parseInt(hex.slice(1), 16);
  const r = (v >> 16) & 255;
  const g = (v >> 8) & 255;
  const bl = v & 255;
  let best = 7;
  let bestD = Infinity;
  for (let i = 1; i < 256; i++) {
    const c = ACI[i];
    if (c == null) continue;
    const d = (((c >> 16) & 255) - r) ** 2 + (((c >> 8) & 255) - g) ** 2 + ((c & 255) - bl) ** 2;
    if (d < bestD) {
      bestD = d;
      best = i;
    }
  }
  aciCache.set(hex, best);
  return best;
}

function dxfText(s) {
  let out = '';
  for (const ch of String(s)) {
    const code = ch.codePointAt(0);
    out += code >= 32 && code < 127 ? ch : `\\U+${code.toString(16).toUpperCase().padStart(4, '0')}`;
  }
  return out;
}

function dxfLayerName(name) {
  const clean = String(name).toUpperCase().replace(/[^A-Z0-9_$-]/g, '_');
  return clean || '0';
}

export function drawingToDXF(drawing, { sheet = null } = {}) {
  const { b, k } = layoutFor(drawing, sheet);
  const n = numFormatter(b);
  const lines = [];
  const w = (code, value) => lines.push(String(code), String(value));

  const layerNames = new Map();
  for (const name of drawing.layers.keys()) layerNames.set(name, dxfLayerName(name));

  // HEADER
  w(0, 'SECTION'); w(2, 'HEADER');
  w(9, '$ACADVER'); w(1, 'AC1009');
  w(9, '$INSUNITS'); w(70, UNITS[drawing.units]?.dxf ?? 4);
  w(9, '$EXTMIN'); w(10, n(b.minX)); w(20, n(b.minY)); w(30, 0);
  w(9, '$EXTMAX'); w(10, n(b.maxX)); w(20, n(b.maxY)); w(30, 0);
  w(9, '$LTSCALE'); w(40, 1);
  w(0, 'ENDSEC');

  // TABLES
  const dash = DASH_MM[0] / k;
  const gap = DASH_MM[1] / k;
  w(0, 'SECTION'); w(2, 'TABLES');
  w(0, 'TABLE'); w(2, 'LTYPE'); w(70, 2);
  w(0, 'LTYPE'); w(2, 'CONTINUOUS'); w(70, 0); w(3, 'Solid line'); w(72, 65); w(73, 0); w(40, 0);
  w(0, 'LTYPE'); w(2, 'DASHED'); w(70, 0); w(3, 'Dashed __ __ __'); w(72, 65); w(73, 2); w(40, n(dash + gap)); w(49, n(dash)); w(49, n(-gap));
  w(0, 'ENDTAB');
  const usedLayers = [...new Set(layerNames.values())];
  if (!usedLayers.includes('0')) usedLayers.unshift('0');
  w(0, 'TABLE'); w(2, 'LAYER'); w(70, usedLayers.length);
  for (const ln of usedLayers) {
    const src = [...drawing.layers.values()].find((L) => dxfLayerName(L.name) === ln);
    const visible = !src || src.visible !== false;
    w(0, 'LAYER'); w(2, ln); w(70, 0);
    w(62, (visible ? 1 : -1) * nearestAci(src ? src.color : null));
    w(6, src && src.lineType === 'dashed' ? 'DASHED' : 'CONTINUOUS');
  }
  w(0, 'ENDTAB');
  w(0, 'TABLE'); w(2, 'STYLE'); w(70, 1);
  w(0, 'STYLE'); w(2, 'STANDARD'); w(70, 0); w(40, 0); w(41, 1); w(50, 0); w(71, 0); w(42, 2.5); w(3, 'txt'); w(4, '');
  w(0, 'ENDTAB');
  w(0, 'ENDSEC');

  // ENTITIES
  w(0, 'SECTION'); w(2, 'ENTITIES');
  for (const e of drawing.entities) {
    const layer = layerNames.get(e.layer) || '0';
    const common = () => {
      w(8, layer);
      if (e.color) w(62, nearestAci(e.color));
      if (e.lineType === 'dashed') w(6, 'DASHED');
    };
    switch (e.type) {
      case 'polyline': {
        const p = e.points;
        if (p.length === 2 && !e.closed) {
          w(0, 'LINE'); common();
          w(10, n(p[0][0])); w(20, n(p[0][1])); w(30, 0);
          w(11, n(p[1][0])); w(21, n(p[1][1])); w(31, 0);
        } else if (e.fill && (p.length === 3 || p.length === 4)) {
          const q = p.length === 3 ? [p[0], p[1], p[2], p[2]] : [p[0], p[1], p[3], p[2]];
          w(0, 'SOLID'); common();
          q.forEach((pt, i) => { w(10 + i, n(pt[0])); w(20 + i, n(pt[1])); w(30 + i, 0); });
        } else {
          w(0, 'POLYLINE'); common(); w(66, 1); w(10, 0); w(20, 0); w(30, 0); w(70, e.closed ? 1 : 0);
          for (const pt of p) {
            w(0, 'VERTEX'); w(8, layer); w(10, n(pt[0])); w(20, n(pt[1])); w(30, 0);
          }
          w(0, 'SEQEND'); w(8, layer);
        }
        break;
      }
      case 'circle':
        w(0, 'CIRCLE'); common(); w(10, n(e.c[0])); w(20, n(e.c[1])); w(30, 0); w(40, n(e.r));
        break;
      case 'arc': {
        const deg = (a) => ((((a * 180) / Math.PI) % 360) + 360) % 360;
        w(0, 'ARC'); common(); w(10, n(e.c[0])); w(20, n(e.c[1])); w(30, 0); w(40, n(e.r));
        w(50, n(deg(e.a0))); w(51, n(deg(e.a0 + normSweep(e.a0, e.a1))));
        break;
      }
      case 'text': {
        const ha = e.align === 'center' ? 1 : e.align === 'right' ? 2 : 0;
        const va = e.valign === 'middle' ? 2 : e.valign === 'top' ? 3 : 0;
        const rot = e.rot || 0;
        String(e.text).split('\n').forEach((line, i) => {
          if (!line) return;
          const dy = -i * e.h * 1.6;
          const x = e.p[0] - dy * Math.sin(rot);
          const y = e.p[1] + dy * Math.cos(rot);
          w(0, 'TEXT'); common();
          w(10, n(x)); w(20, n(y)); w(30, 0); w(40, n(e.h)); w(1, dxfText(line));
          if (rot) w(50, n((rot * 180) / Math.PI));
          if (ha) w(72, ha);
          if (ha || va) { w(11, n(x)); w(21, n(y)); w(31, 0); }
          if (va) w(73, va);
        });
        break;
      }
      default:
        break;
    }
  }
  w(0, 'ENDSEC');
  w(0, 'EOF');
  return lines.join('\r\n') + '\r\n';
}

/* ------------------------------------------------------------------ PDF */

function hexToRgb(hex) {
  const v = parseInt((hex || '#000000').slice(1), 16);
  return [(v >> 16) & 255, (v >> 8) & 255, v & 255];
}

function rasterizeText(text, heightMM, color) {
  const pxPerMM = 12;
  const fontPx = Math.max(8, heightMM * 1.4 * pxPerMM);
  const canvas = document.createElement('canvas');
  const ctx = canvas.getContext('2d');
  const font = `${fontPx}px 'Leelawadee UI', Tahoma, 'Noto Sans Thai', 'IBM Plex Sans Thai', sans-serif`;
  ctx.font = font;
  const m = ctx.measureText(text);
  canvas.width = Math.ceil(m.width + fontPx * 0.2);
  canvas.height = Math.ceil(fontPx * 1.5);
  ctx.font = font;
  ctx.fillStyle = color;
  ctx.textBaseline = 'alphabetic';
  ctx.fillText(text, fontPx * 0.1, fontPx * 1.1);
  return { url: canvas.toDataURL('image/png'), wMM: canvas.width / pxPerMM, hMM: canvas.height / pxPerMM, baseMM: (fontPx * 1.1) / pxPerMM, padMM: (fontPx * 0.1) / pxPerMM };
}

export async function drawingToPDF(drawing, { sheet = null, paper = 'fit' } = {}) {
  const { jsPDF } = await import('jspdf');
  let pageW;
  let pageH;
  let k;
  let map;
  let baseWeight = 0.25;

  if (sheet) {
    [pageW, pageH] = sheet.paperSize;
    k = sheet.k;
    const f = sheet.frame;
    map = (x, y) => [(x - f.minX) * k, pageH - (y - f.minY) * k];
  } else {
    const b = drawingBounds(drawing);
    if (!boundsValid(b)) throw new Error('DRAWING_EMPTY');
    const bw = Math.max(b.maxX - b.minX, 1e-9);
    const bh = Math.max(b.maxY - b.minY, 1e-9);
    const toMM = UNITS[drawing.units]?.toMM || 1;
    const margin = 10;
    if (paper === 'fit') {
      k = toMM;
      const maxSide = 1189 - 2 * margin;
      if (Math.max(bw, bh) * k > maxSide) k = maxSide / Math.max(bw, bh);
      pageW = Math.max(60, bw * k + 2 * margin);
      pageH = Math.max(60, bh * k + 2 * margin);
    } else {
      const [pw, ph] = PAPERS[paper] || PAPERS.A4;
      const landscape = bw >= bh;
      pageW = landscape ? pw : ph;
      pageH = landscape ? ph : pw;
      k = Math.min((pageW - 2 * margin) / bw, (pageH - 2 * margin) / bh);
    }
    const ox = (pageW - bw * k) / 2;
    const oy = (pageH - bh * k) / 2;
    map = (x, y) => [ox + (x - b.minX) * k, pageH - (oy + (y - b.minY) * k)];
    baseWeight = 0.2;
  }

  const doc = new jsPDF({ orientation: pageW >= pageH ? 'landscape' : 'portrait', unit: 'mm', format: [pageW, pageH], compress: true });
  doc.setProperties({ title: drawing.meta.title || 'Drawing', creator: 'MorphCAD' });
  doc.setLineCap('round');
  doc.setLineJoin('round');

  const drawChain = (pts, closed, style) => {
    if (pts.length < 2) return;
    const mapped = pts.map(([x, y]) => map(x, y));
    const deltas = [];
    for (let i = 1; i < mapped.length; i++) deltas.push([mapped[i][0] - mapped[i - 1][0], mapped[i][1] - mapped[i - 1][1]]);
    doc.lines(deltas, mapped[0][0], mapped[0][1], [1, 1], style, closed);
  };

  const extent = (() => {
    const b = drawingBounds(drawing);
    return Math.max(b.maxX - b.minX, b.maxY - b.minY);
  })();

  for (const e of drawing.entities) {
    if (!isLayerVisible(drawing, e.layer)) continue;
    const hex = resolveColor(drawing, e) || '#000000';
    const [r, g, bl] = hexToRgb(hex);
    if (e.type === 'text') {
      const hMM = e.h * k;
      const rotDeg = ((e.rot || 0) * 180) / Math.PI;
      const linesOf = String(e.text).split('\n');
      linesOf.forEach((line, i) => {
        if (!line) return;
        const dy = -i * e.h * 1.6;
        const rot = e.rot || 0;
        const [x, y] = map(e.p[0] - dy * Math.sin(rot), e.p[1] + dy * Math.cos(rot));
        if (/^[\x20-\x7E]*$/.test(line)) {
          doc.setFont('helvetica', 'normal');
          doc.setFontSize((hMM * 1.4) / 0.3528);
          doc.setTextColor(r, g, bl);
          doc.text(line, x, y, {
            angle: rotDeg,
            align: e.align === 'center' ? 'center' : e.align === 'right' ? 'right' : 'left',
            baseline: e.valign === 'middle' ? 'middle' : e.valign === 'top' ? 'top' : 'alphabetic',
          });
        } else {
          const img = rasterizeText(line, hMM, hex);
          let left = x - img.padMM;
          if (e.align === 'center') left = x - img.wMM / 2;
          else if (e.align === 'right') left = x - img.wMM + img.padMM;
          let top = y - img.baseMM;
          if (e.valign === 'middle') top += hMM / 2;
          else if (e.valign === 'top') top += hMM;
          doc.addImage(img.url, 'PNG', left, top, img.wMM, img.hMM, undefined, 'FAST', rotDeg);
        }
      });
      continue;
    }
    const weight = sheet ? resolveWeight(drawing, e) : baseWeight;
    doc.setDrawColor(r, g, bl);
    doc.setLineWidth(weight);
    doc.setLineDashPattern(resolveLineType(drawing, e) === 'dashed' ? DASH_MM : [], 0);
    if (e.type === 'polyline') {
      if (e.fill) doc.setFillColor(r, g, bl);
      drawChain(e.points, !!e.closed, e.fill ? 'FD' : 'S');
    } else if (e.type === 'circle') {
      const [x, y] = map(e.c[0], e.c[1]);
      doc.circle(x, y, e.r * k, 'S');
    } else if (e.type === 'arc') {
      drawChain(arcPoints(e.c, e.r, e.a0, e.a1, extent), false, 'S');
    }
  }

  return doc.output('blob');
}
